// Ключ для пошуку деталей: точна назва → база → префікс «X: …»
function lookup(name) {
  if (D[name]) return D[name];
  const b = baseName(name);
  if (D[b]) return D[b];
  if (/^Божественний канал|^Канал:/.test(name)) return D['Божественний канал'];
  if (/^Драконячий родовід:/.test(name)) return D['Драконячий родовід'];
  if (/^Бойовий стиль:|^Додатковий бойовий стиль:/.test(name)) return null;
  const pre = name.split(':')[0];
  return D[pre] || null;
}

export function featureDetails(sheet, feature) {
  const fn = lookup(feature.name);
  const c = ctxOf(sheet);
  const extra = fn ? fn(c) : {};
  return { stats: extra.stats || [], lines: extra.lines || [] };
}

