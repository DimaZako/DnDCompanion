const AUTO = Object.keys(ABBR).filter((k) => k.length > 1).sort((a, b) => b.length - a.length);
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
export const ABBR_RE = new RegExp(`(?<![\\p{L}\\p{N}])(\\d*к(?:100|20|12|10|8|6|4)(?![\\p{L}\\p{N}])|${AUTO.map(escRe).join('|')})(?![\\p{L}])`, 'gu');

const DIE_NAME = { 4: 'чотиригранна', 6: 'шестигранна', 8: 'восьмигранна', 10: 'десятигранна', 12: 'дванадцятигранна', 20: 'двадцятигранна' };
export function diceInfo(t) {
  const m = String(t).match(/^(\d*)к(\d+)$/);
  if (!m) return null;
  const n = Number(m[1] || 1);
  const d = Number(m[2]);
  if (d === 100) return ['Відсотковий кидок (к100)', 'Кидаються дві к10: одна — десятки, друга — одиниці. Результат від 1 до 100.'];
  const one = `к${d} — ${DIE_NAME[d] || `${d}-гранна`} кістка.`;
  return [`${n > 1 ? n : ''}к${d}`, n > 1 ? `Кинь ${n} кістки к${d} і склади результати: від ${n} до ${n * d}. ${one}` : `Кинь одну кістку: від 1 до ${d}. ${one}`];
}

